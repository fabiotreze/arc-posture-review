#!/usr/bin/env python3
"""Renders criteria/v4/sources.json as docs/sources.en-US.md and docs/sources.pt-BR.md. Use --check to fail when they are stale."""
import json, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REGISTER = ROOT / "criteria/v4/sources.json"
LABEL = {
    "en-US": {
        "VERIFIED_OFFICIAL": "Official source", "VERIFIED_CVE": "Official CVE record", "KIT_CRITERION": "Kit criterion", "UNVERIFIED": "To verify",
        "title": "# Sources and foundation of the claims",
        "intro": "Every threshold, date and label used by the collector and the reports is registered in `criteria/v4/sources.json` with the state of its foundation. This page is generated by `tools/Sync-Sources.py`; `tools/Test-ClaimRegister.py` fails when the collector gains a threshold that is not registered.",
        "legend": "## How to read the state",
        "states": {
            "VERIFIED_OFFICIAL": "the Microsoft page was opened in full and the quoted statement supports the claim.",
            "VERIFIED_CVE": "confirmed in the NVD record of the CVE, which cites the MSRC advisory.",
            "KIT_CRITERION": "a criterion of this kit, **not** a Microsoft recommendation; the rationale says why it exists.",
            "UNVERIFIED": "not yet confirmed in an official source; the result is shown but must not be presented as official until the to-do is closed.",
        },
        "summary": "## Summary", "claim": "Claim", "checks": "Checks", "state": "State", "source": "Source or note", "verified": "Verified on", "id": "Id",
        "detail": "## Entries", "evidence": "Evidence", "rationale": "Rationale", "todo": "To do", "review": "Review by",
    },
    "pt-BR": {
        "VERIFIED_OFFICIAL": "Fonte oficial", "VERIFIED_CVE": "Registro oficial de CVE", "KIT_CRITERION": "Critério do kit", "UNVERIFIED": "A verificar",
        "title": "# Fontes e fundamento das afirmações",
        "intro": "Cada limiar, data e rótulo usado pelo coletor e pelos relatórios está registrado em `criteria/v4/sources.json` com o estado do seu fundamento. Esta página é gerada por `tools/Sync-Sources.py`; o `tools/Test-ClaimRegister.py` falha quando o coletor ganha um limiar que não está registrado.",
        "legend": "## Como ler o estado",
        "states": {
            "VERIFIED_OFFICIAL": "a página da Microsoft foi aberta por inteiro e o trecho citado sustenta a afirmação.",
            "VERIFIED_CVE": "confirmado no registro do CVE no NVD, que cita o aviso do MSRC.",
            "KIT_CRITERION": "um critério deste kit, **não** uma recomendação da Microsoft; a justificativa diz por que ele existe.",
            "UNVERIFIED": "ainda não confirmado em fonte oficial; o resultado aparece, mas não deve ser apresentado como oficial até a pendência ser fechada.",
        },
        "summary": "## Resumo", "claim": "Afirmação", "checks": "Verificações", "state": "Estado", "source": "Fonte ou nota", "verified": "Verificado em", "id": "Id",
        "detail": "## Registros", "evidence": "Evidência", "rationale": "Justificativa", "todo": "Pendência", "review": "Rever até",
    },
}


def cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def render(data: dict, lang: str) -> str:
    L = LABEL[lang]
    out = [L["title"], "", L["intro"], "", L["legend"], ""]
    out += [f"- **{L[k]}**: {L['states'][k]}" for k in ("VERIFIED_OFFICIAL", "VERIFIED_CVE", "KIT_CRITERION", "UNVERIFIED")]
    out += ["", L["summary"], "", f"| {L['id']} | {L['claim']} | {L['checks']} | {L['state']} | {L['verified']} |", "|---|---|---|---|---|"]
    for e in data["entries"]:
        out.append(f"| `{e['id']}` | {cell(e['claim'][lang])} | {', '.join(e['checks']) or '-'} | {L[e['status']]} | {e['verifiedOn']} |")
    out += ["", L["detail"], ""]
    for e in data["entries"]:
        out += [f"### {e['id']} — {L[e['status']]}", "", e["claim"][lang], ""]
        if e.get("evidence"):
            out += [f"- **{L['evidence']}:** {e['evidence']}"]
        if e.get("rationale"):
            out += [f"- **{L['rationale']}:** {e['rationale']}"]
        if e.get("todo"):
            out += [f"- **{L['todo']}:** {e['todo']}"]
        for s in e.get("sources", []):
            out += [f"- [{s['title']}]({s['url']})"]
        if e.get("reviewBy"):
            out += [f"- **{L['review']}:** {e['reviewBy']}"]
        out += [""]
    return "\n".join(out).rstrip() + "\n"


def main() -> int:
    data = json.loads(REGISTER.read_text(encoding="utf-8"))
    stale = []
    for lang in ("en-US", "pt-BR"):
        target = ROOT / "docs" / f"sources.{lang}.md"
        text = render(data, lang)
        if "--check" in sys.argv:
            current = target.read_bytes().decode("utf-8").replace("\r\n", "\n") if target.exists() else ""
            if current != text:
                stale.append(str(target.relative_to(ROOT)))
        else:
            target.write_bytes(text.encode("utf-8"))
            print(f"[OK] {target.relative_to(ROOT)}")
    if stale:
        print("[FAIL] stale: " + ", ".join(stale) + " (run python tools/Sync-Sources.py)")
        return 1
    if "--check" in sys.argv:
        print("[PASS] docs/sources.*.md match criteria/v4/sources.json")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
