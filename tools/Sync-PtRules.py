#!/usr/bin/env python3
"""Regenerates criteria/v4/pt-br-detail-rules.json from the Portuguese rule tables of arc-posture-review.pt-BR.html (the app is the source)."""
import json, re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
APP = ROOT / "arc-posture-review.pt-BR.html"
OUT = ROOT / "criteria/v4/pt-br-detail-rules.json"
LINE = re.compile(r'^\[/(.*)/([gimsuy]*),\s*("(?:[^"\\]|\\.)*")\],?$')


def build() -> dict:
    text = APP.read_text(encoding="utf-8")
    exact_block = re.search(r"var PT_DETAIL_EXACT = (\{.*?\r?\n  \});", text, re.S).group(1)
    exact = {k: v for rows in json.loads(exact_block).values() for k, v in rows.items()}
    rules_block = re.search(r"var PT_DETAIL_RULES = \[\r?\n(.*?)\r?\n  \];", text, re.S).group(1)
    rules = []
    for line in rules_block.splitlines():
        if not line.strip():
            continue
        match = LINE.match(line.strip())
        if not match:
            sys.exit("[FAIL] unparsable rule line: " + line.strip()[:120])
        rules.append([match.group(1), match.group(2), json.loads(match.group(3))])
    narrative_block = re.search(r"function ptEvidenceNarrative\(raw\) \{(.*?)\r?\n  \}", text, re.S).group(1)
    narrative = [[m.group(1), m.group(2), json.loads(m.group(3))]
                 for m in re.finditer(r'\.replace\(/(.*?)/([gimsuy]*),\s*("(?:[^"\\]|\\.)*")\)', narrative_block)]
    return {"_comment": "Portuguese (pt-BR) rendering rules for collector text in the v4 report. Generated by tools/Sync-PtRules.py from PT_DETAIL_EXACT, PT_DETAIL_RULES and ptEvidenceNarrative of arc-posture-review.pt-BR.html; tools/Test-PtBrContent.py checks the parity.",
            "exact": exact, "rules": rules, "narrative": narrative}


if __name__ == "__main__":
    data = build()
    OUT.write_text(json.dumps(data, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    print(f"[OK] {OUT.relative_to(ROOT)}: {len(data['rules'])} rules, {len(data['exact'])} exact, {len(data['narrative'])} narrative")
